@pytest.mark.slow
def test_the_worked_example_is_produced_on_request(screen, qapp):
    """It is generated by the narrator through the real subprocess, not stored,
    so what the lesson shows cannot drift from what the tool would say."""
    from PySide6.QtCore import QThreadPool

    screen.listing.setCurrentRow(0)
    qapp.processEvents()
    lesson = screen.current_lesson()

    assert not screen.example_steps.isVisibleTo(screen)
    screen._work(lesson.example, lesson.example_conditions, lesson.narrator,
                 screen.example_steps, screen.example_button)
    QThreadPool.globalInstance().waitForDone(90_000)
    for _ in range(6):
        qapp.processEvents()

    assert screen.example_steps.isVisibleTo(screen)
    assert screen.example_steps._body.count() >= 4
    assert screen.example_button.isEnabled(), "the button was left disabled"
